local rules = require("zyt.rules")

describe("rules.normalise", function()
  it("fills the defaults from an empty file", function()
    local r = assert(rules.normalise({}, "/Users/me"))
    assert.equals("work", r.defaultClass)
    assert.equals(30, r.tickSeconds)
    assert.equals(120, r.typingSeconds)
    assert.same({ "/Users/me/git" }, r.repoRoots)
    assert.same({ work = "W", private = "P", away = "·" }, r.labels)
  end)

  it("keeps what the file says and expands the home directory", function()
    local r = assert(rules.normalise({
      defaultClass = "private",
      labels = { work = "A" },
      repoRoots = { "~/code/", "/srv/git" },
      noIdleApps = { "Teams" },
      apps = { Mail = "work", iTerm2 = "repo" },
      titles = { { contains = "Jira", class = "work" } },
      remotes = { { match = "github.com", class = "private" } },
    }, "/Users/me"))
    assert.equals("private", r.defaultClass)
    assert.equals("A", r.labels.work)
    assert.equals("P", r.labels.private)
    assert.same({ "/Users/me/code", "/srv/git" }, r.repoRoots)
    assert.is_true(r.noIdleApps["Teams"])
    assert.equals("repo", r.apps.iTerm2)
    assert.same({ { contains = "Jira", class = "work" } }, r.titles)
    assert.same({ { match = "github.com", class = "private" } }, r.remotes)
  end)

  it("fills and checks the prompt", function()
    local r = assert(rules.normalise({ prompt = { seconds = 5 } }, "/h"))
    assert.same({ enabled = true, seconds = 5, cooldownSeconds = 1800 }, r.prompt)
    local _, err = rules.normalise({ prompt = { enabled = "yes" } }, "/h")
    assert.matches("prompt.enabled", err)
    _, err = rules.normalise({ prompt = 3 }, "/h")
    assert.matches("prompt has to be", err)
  end)

  it("lets the panel wait for an answer but not the cooldown", function()
    local r = assert(rules.normalise({}, "/h"))
    assert.equal(0, r.prompt.seconds)
    r = assert(rules.normalise({ prompt = { seconds = 0 } }, "/h"))
    assert.equal(0, r.prompt.seconds)
    local _, err = rules.normalise({ prompt = { seconds = -1 } }, "/h")
    assert.matches("prompt.seconds", err)
    _, err = rules.normalise({ prompt = { cooldownSeconds = 0 } }, "/h")
    assert.matches("prompt.cooldownSeconds", err)
  end)

  it("fills and checks the calendar", function()
    local r = assert(rules.normalise({ meetings = { enabled = true, minimumSeconds = 60 } }, "/h"))
    assert.is_true(r.meetings.enabled)
    assert.equal(60, r.meetings.minimumSeconds)
    assert.equal("work", r.meetings.class)
    assert.same({ "busy", "oof", "tentative" }, r.meetings.statuses)
    -- the tenant and the app the command line signs in with are none of the
    -- Spoon's business, and a file that carries them still reads
    assert(rules.normalise({ meetings = { tenantId = "t", clientId = "c" } }, "/h"))
    local _, err = rules.normalise({ meetings = { class = "sometimes" } }, "/h")
    assert.matches("meetings.class", err)
    _, err = rules.normalise({ meetings = { statuses = { "" } } }, "/h")
    assert.matches("meetings.statuses%[1%]", err)
    _, err = rules.normalise({ meetings = { minimumSeconds = -1 } }, "/h")
    assert.matches("meetings.minimumSeconds", err)
    _, err = rules.normalise({ meetings = 3 }, "/h")
    assert.matches("meetings has to be", err)
    -- a timer asked to fire every zero seconds never stops firing
    _, err = rules.normalise({ meetings = { syncHours = 0 } }, "/h")
    assert.matches("meetings.syncHours", err)
  end)

  it("names the field that is wrong", function()
    local _, err = rules.normalise({ defaultClass = "fun" }, "/h")
    assert.matches("defaultClass", err)
    _, err = rules.normalise({ apps = { Mail = "sometimes" } }, "/h")
    assert.matches('apps%["Mail"%]', err)
    _, err = rules.normalise({ titles = { { class = "work" } } }, "/h")
    assert.matches("titles%[1%]", err)
    _, err = rules.normalise({ remotes = { { match = "x", class = "y" } } }, "/h")
    assert.matches("remotes%[1%]", err)
    _, err = rules.normalise({ tickSeconds = 0 }, "/h")
    assert.matches("tickSeconds", err)
    _, err = rules.normalise({ typingSeconds = 0 }, "/h")
    assert.matches("typingSeconds", err)
    _, err = rules.normalise({ repoRoots = { 3 } }, "/h")
    assert.matches("repoRoots%[1%]", err)
    _, err = rules.normalise({ apps = "Mail" }, "/h")
    assert.matches("apps", err)
    _, err = rules.normalise("nope", "/h")
    assert.matches("JSON object", err)
  end)
end)
